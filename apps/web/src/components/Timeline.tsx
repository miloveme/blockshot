"use client";

import { useStudio } from "@/lib/store";
import { startRecording, stopRecording } from "@/lib/recorder";

const SHOT_COLORS = ["#3b82f6", "#f59e0b", "#10b981", "#ef4444", "#8b5cf6", "#ec4899"];

function timecode(t: number, fps: number) {
  const s = Math.floor(t);
  const f = Math.round((t - s) * fps) % fps;
  return `${String(Math.floor(s / 60)).padStart(2, "0")}:${String(s % 60).padStart(2, "0")}:${String(f).padStart(2, "0")}`;
}

const KEY_PROPS = ["position", "rotation", "focalLength", "pose"] as const;

/** Keys of the selected object. Yellow = manual (editable via K), grey = generated by actions. */
function KeyLane() {
  const selection = useStudio((s) => s.selection);
  const compiled = useStudio((s) => s.compiled);
  const spec = useStudio((s) => s.spec);
  const { setTime } = useStudio.getState();
  if (!selection) return null;
  const { duration } = spec.settings;
  const marks = new Map<number, boolean>(); // time → has a manual key
  for (const prop of KEY_PROPS) {
    const keys = compiled.tracks.get(`${selection}/${prop}`);
    if (!keys || keys.length < 2) continue;
    const manual = spec.tracks.some((t) => t.target === selection && t.property === prop);
    for (const k of keys) {
      const t = Math.round(k.t * 100) / 100;
      marks.set(t, (marks.get(t) ?? false) || manual);
    }
  }
  return (
    <div className="relative mb-1 h-3" title="선택한 오브젝트의 키 (K: 추가, Alt+K: 삭제)">
      {[...marks].map(([t, manual]) => (
        <button
          key={t}
          onClick={() => setTime(t)}
          className={`absolute top-0 h-2.5 w-2.5 -translate-x-1/2 rotate-45 ${manual ? "bg-amber-400" : "bg-zinc-500"}`}
          style={{ left: `${(t / duration) * 100}%` }}
        />
      ))}
    </div>
  );
}

export function Timeline() {
  const time = useStudio((s) => s.time);
  const playing = useStudio((s) => s.playing);
  const recording = useStudio((s) => s.recording);
  const spec = useStudio((s) => s.spec);
  const { setTime, setPlaying } = useStudio.getState();
  const { duration, fps } = spec.settings;

  return (
    <div className="flex items-center gap-3 border-t border-white/10 bg-[#15171c] px-4 py-3 text-xs text-zinc-300">
      <button
        className="w-16 rounded bg-white/10 px-3 py-1.5 font-medium hover:bg-white/20 disabled:opacity-40"
        onClick={() => setPlaying(!playing)}
        disabled={!!recording}
        title="Space"
      >
        {playing ? "❚❚ 정지" : "▶ 재생"}
      </button>
      <button
        className={`rounded px-2.5 py-1.5 font-medium ${recording ? "animate-pulse bg-red-600 text-white" : "bg-white/10 text-red-300 hover:bg-white/20"}`}
        onClick={() => (recording ? stopRecording() : startRecording())}
        title="선택한 인물/카메라를 재생하면서 키보드로 움직여 동선을 기록합니다 (R)"
      >
        {recording ? "■ 녹화 정지" : "● REC"}
      </button>
      <span className="w-24 font-mono tabular-nums">{timecode(time, fps)}</span>
      <div className="relative flex-1">
        <div className="relative mb-1 h-5">
          {spec.shots.map((s, i) => (
            <button
              key={s.id}
              className="absolute top-0 h-5 truncate rounded px-1 text-left text-[10px] font-semibold text-white/90"
              style={{
                left: `${(s.start / duration) * 100}%`,
                width: `${((s.end - s.start) / duration) * 100}%`,
                background: SHOT_COLORS[i % SHOT_COLORS.length],
              }}
              onClick={() => setTime(s.start)}
              title={s.description}
            >
              {s.id} · {s.camera}
            </button>
          ))}
        </div>
        <KeyLane />
        <input
          type="range"
          min={0}
          max={duration}
          step={1 / fps}
          value={time}
          onChange={(e) => setTime(Number(e.target.value))}
          className="w-full accent-amber-400"
        />
      </div>
      <span className="w-20 text-right font-mono tabular-nums text-zinc-500">
        f{Math.round(time * fps)} / {Math.round(duration * fps)}
      </span>
    </div>
  );
}
