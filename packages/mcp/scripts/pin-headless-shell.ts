/**
 * Pins the renderer the local server downloads: the current Chrome for Testing *stable* chrome-headless-shell, with the
 * size and SHA-256 of every platform's zip (each zip is downloaded once here to hash it, ~700 MB in all).
 * Writes src/headless-shell.generated.ts. Run it to move to a newer Chromium, then rebuild the MCP bundle:
 *
 *   pnpm --filter @blockshot/mcp pin:browser && pnpm --filter @blockshot/mcp build
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { SHELL_PLATFORMS, shellZipUrl } from "../src/browser";

const here = dirname(fileURLToPath(import.meta.url));
const index = (await (await fetch("https://googlechromelabs.github.io/chrome-for-testing/last-known-good-versions-with-downloads.json")).json()) as {
  channels: { Stable: { version: string } };
};
const version = index.channels.Stable.version;
const files: Record<string, { size: number; sha256: string }> = {};
for (const platform of SHELL_PLATFORMS) {
  const res = await fetch(shellZipUrl(version, platform));
  if (!res.ok || !res.body) throw new Error(`${platform}: HTTP ${res.status}`);
  const hash = createHash("sha256");
  let size = 0;
  for await (const chunk of res.body as unknown as AsyncIterable<Uint8Array>) {
    hash.update(chunk);
    size += chunk.length;
  }
  files[platform] = { size, sha256: hash.digest("hex") };
  console.log(`${platform}: ${(size / 1024 / 1024).toFixed(1)} MB ${files[platform]!.sha256}`);
}
const out = resolve(here, "../src/headless-shell.generated.ts");
writeFileSync(
  out,
  `// generated by scripts/pin-headless-shell.ts — do not edit\nexport const HEADLESS_SHELL = ${JSON.stringify({ version, files }, null, 2)} as const;\n`,
);
console.log(`pinned chrome-headless-shell ${version} → ${out}`);
