/**
 * Bundles the script runtime (scene builder + helpers) into one IIFE string for the QuickJS sandbox used by the remote MCP
 * endpoint (apps/web/src/server). Run after changing builder.ts / motion.ts: `pnpm gen:sandbox`.
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const out = await build({
  entryPoints: [resolve(here, "../src/sandbox-entry.ts")],
  bundle: true,
  write: false,
  format: "iife",
  target: "es2020",
  platform: "neutral",
  minify: true,
  legalComments: "none",
});
const code = out.outputFiles[0]!.text;
const target = resolve(here, "../../../apps/web/src/server/sandbox-runtime.generated.ts");
writeFileSync(target, `// GENERATED by packages/core/scripts/gen-sandbox.ts — do not edit. Run \`pnpm gen:sandbox\`.\nexport const SANDBOX_RUNTIME = ${JSON.stringify(code)};\n`);
console.log(`sandbox runtime: ${(code.length / 1024).toFixed(0)} KB → ${target}`);
